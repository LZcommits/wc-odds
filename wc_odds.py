def _crowd_picks(slug, grid, mn, cnh, cna, rows=None):
    """返回大众胜平负 + 大众比分推荐列表（供 grade_bets 和 build_past_detail 共用）。"""
    cd = CROWD_DATA.get(slug)
    if not cd: return None, []
    label = {'home': cnh, 'draw': '平局', 'away': cna}
    total_v = sum(v for _, v in cd['top'])
    scored_n = cd.get('scored', total_v) or 1
    # 大众胜平负
    wdl_v = {'home': 0, 'draw': 0, 'away': 0}
    for s, v in cd['top']:
        h, a = map(int, s.split('-'))
        if h > a: wdl_v['home'] += v
        elif h == a: wdl_v['draw'] += v
        else: wdl_v['away'] += v
    cwd = max(wdl_v, key=wdl_v.get)
    cwd_pct = round(wdl_v[cwd] / max(sum(wdl_v.values()), 1) * 100)
    crowd_wdl = {
        'grade': 'O', 'pick': label[cwd], 'outcome': cwd,
        'odds': 0, 'mkt_pct': 0, 'my_pct': cwd_pct,
        'meta': f'大众投票 {cwd_pct}%<br>共{total_v}票',
        'bet_label': label[cwd], 'match': mn,
    }
    # 大众比分推荐（有赔率：价差比≥1.5；无赔率：票选≥5%，最多3个）
    # 优先读 JSONL 实时赔率（每小时自动采样），回退到静态字典
    live_scr = {}
    if rows:
        for row in reversed(rows):
            sc = row.get('pin_scores') or {}
            if sc.get('odds'):
                live_scr = sc['odds']; break
    slug_odds = live_scr or CROWD_SCORE_ODDS.get(slug, {})
    has_any_odds = any(slug_odds.get(s) for s, _ in cd['top'])
    cands = []
    for s, votes in cd['top']:
        od = slug_odds.get(s)
        vote_share = votes / scored_n
        vote_pct = round(vote_share * 100, 1)
        if od:
            implied = 1 / od
            ratio = vote_share / implied
            if ratio < 1.5: continue
            mkt_pct = round(100 / od)
            grade = 'S' if ratio >= 2.0 else 'O'
            meta = f'赔率：{od}<br>市场预估{mkt_pct}%<br>大众票选{vote_pct}%'
        else:
            if has_any_odds: continue        # 有赔率库但该比分无赔率，跳过
            if vote_share < 0.05: continue   # 无赔率时：票选≥5% 才展示
            ratio = 0; mkt_pct = 0; grade = 'O'
            meta = f'大众票选{vote_pct}%<br>暂无赔率参照'
        cands.append({
            'grade': grade, 'score': s, 'pick': s.replace('-', ':'),
            'odds': od or 0, 'mkt_pct': mkt_pct, 'my_pct': vote_pct,
            'meta': meta,
            'bet_label': f'比分 {s.replace("-",":")}'  , 'match': mn, 'ratio': ratio,
        })
    cands.sort(key=lambda x: -x['ratio'] if x['ratio'] else -x['my_pct'])
    return crowd_wdl, cands[:3]


def grade_bets(cfg, rows, rich, grid):
    """对每场比赛评级：赔率胜平负/大众胜平负/赔率比分×3/大众比分×3/进球数。"""
    slug = cfg['slug']; my = cfg['my']
    mn = f'{cfg["cn_h"]} vs {cfg["cn_a"]}'
    result = {}

    # ── 1. 赔率推测胜平负 ────────────────────────────────────────
    if rows:
        p = rows[-1].get('pin_h2h')
        if p:
            evs = {k: my[k] * p[k] for k in ('home','draw','away')}
            best_k = max(evs, key=evs.get)
            fav_k = min(p, key=p.get); fav_od = p[fav_k]
            label = {'home': cfg['cn_h'], 'draw': '平局', 'away': cfg['cn_a']}
            if fav_od < 1.5 and best_k == fav_k: best_k = 'draw'
            od = p[best_k]; ev = evs[best_k]
            mkt_pct = round(100/od); my_pct = round(my[best_k]*100)
            drift_warn = ''
            if len(rows) >= 5:
                f1 = rows[0].get('pin_h2h'); f2 = rows[-1].get('pin_h2h')
                if f1 and f2:
                    md = max(abs(f1[k]-f2[k]) for k in ('home','draw','away'))
                    if md > 0.3: drift_warn = f' · ⚠漂移{md:.2f}'
            if ev >= 1.08 and my[best_k] >= 0.12: grade = 'S'
            elif ev >= 1.02 and my[best_k] >= 0.07: grade = 'O'
            else: grade = 'X'
            if drift_warn and grade == 'S': grade = 'O'
            result['wdl'] = {
                'grade': grade, 'pick': label[best_k], 'outcome': best_k,
                'odds': od, 'mkt_pct': mkt_pct, 'my_pct': my_pct,
                'meta': f'赔率：{od}<br>市场预估{mkt_pct}%<br>模型预估{my_pct}%{drift_warn}',
                'bet_label': label[best_k], 'match': mn, 'ev': round(ev, 2),
            }

    # ── 2. 大众推测胜平负 + 大众比分 ─────────────────────────────
    crowd_wdl, crowd_scores = _crowd_picks(slug, grid, mn, cfg['cn_h'], cfg['cn_a'], rows=rows)
    if crowd_wdl: result['crowd_wdl'] = crowd_wdl
    for i, cp in enumerate(crowd_scores): result[f'crowd_score{i+1}'] = cp

    # ── 3. 赔率推测比分（满足规则，最多3个）────────────────────────
    so = (rich.get('score_odds') or {}).get('odds', {})
    cands = []
    for sc, prob in sorted(grid.items(), key=lambda x: -x[1]):
        od = so.get(sc)
        if not od: continue
        if 6.0 <= od < 8.0 and prob >= 0.05: grade = 'S'
        elif od <= 9.0 and prob >= 0.04: grade = 'O'
        else: continue  # 不满足规则直接跳过
        mkt_pct = round(100/od); my_pct = round(prob*100, 1)
        cands.append({
            'grade': grade, 'score': sc, 'pick': sc.replace('-',':'),
            'odds': od, 'mkt_pct': mkt_pct, 'my_pct': my_pct, 'ev': round(prob*od, 2),
            'meta': f'赔率：{od}<br>市场预估{mkt_pct}%<br>模型预估{my_pct}%',
            'bet_label': f'比分 {sc.replace("-",":")}', 'match': mn,
        })
    cands.sort(key=lambda x: 0 if x['grade']=='S' else 1)
    for i, c in enumerate(cands[:3]): result[f'score{i+1}'] = c

    # ── 4. 大小球 ────────────────────────────────────────────────
    if rows:
        t25 = rows[-1].get('pin_tot25') or {}
        u_od = t25.get('under'); o_od = t25.get('over')
        if u_od and o_od:
            ov_prob = sum(pv for s, pv in grid.items() if sum(map(int, s.split('-'))) > 2)
            un_prob = 1 - ov_prob
            ev_over = ov_prob * o_od; ev_under = un_prob * u_od
            if u_od > 2.1:
                od, prob, ev, pick, pick_dir = o_od, ov_prob, ev_over, '大球 ≥3', 'over'
                grade = 'S' if ev >= 1.08 else 'O'
            elif u_od < 1.65:
                od, prob, ev, pick, pick_dir = u_od, un_prob, ev_under, '小球 ≤2', 'under'
                grade = 'S' if ev >= 1.05 else 'O'
            elif ev_over > ev_under and ev_over >= 1.04:
                od, prob, ev, pick, pick_dir = o_od, ov_prob, ev_over, '大球 ≥3', 'over'; grade = 'O'
            elif ev_under >= 1.04:
                od, prob, ev, pick, pick_dir = u_od, un_prob, ev_under, '小球 ≤2', 'under'; grade = 'O'
            else:
                od, prob, ev, pick, pick_dir = 0, 0, 0, '市场高效', ''; grade = 'X'
            mkt_pct = round(100/od) if od else 0; my_pct = round(prob*100) if prob else 0
            result['goals'] = {
                'grade': grade, 'pick': pick, 'pick_dir': pick_dir,
                'odds': od, 'mkt_pct': mkt_pct, 'my_pct': my_pct, 'ev': round(ev, 2),
                'meta': f'赔率：{od}<br>市场预估{mkt_pct}%<br>模型预估{my_pct}%' if od else '等待赔率采样',
                'bet_label': pick, 'match': mn,
            }
        else:
            result['goals'] = {'grade': 'X', 'pick': '暂无数据', 'pick_dir': '', 'odds': 0,
                               'mkt_pct': 0, 'my_pct': 0, 'ev': 0,
                               'meta': '等待大小球赔率采样', 'bet_label': '', 'match': mn}
    return result


def rec_card_block(grades, slug, is_past=False, past_hits=None):
    """渲染推荐卡：拆成 AI推荐 + 深度推荐 两张卡。"""
    if past_hits is None: past_hits = {}
    BADGE = {'S': '<span class="badge-s">强推荐</span>',
             'O': '<span class="badge-o">推荐</span>',
             'X': '<span class="badge-x">不推荐</span>'}

    def make_row(key, label, required=False):
        g = grades.get(key) or {}
        if not g and not required: return ''
        grade = g.get('grade', 'X')
        pick  = g.get('pick', '—')
        meta  = g.get('meta', '')
        badge = BADGE.get(grade, '')
        if is_past:
            hit = past_hits.get(key)
            if hit is True:    hit_tag = '<span class="rec-hit ok">✓</span>'
            elif hit is False: hit_tag = '<span class="rec-hit no">✗</span>'
            else:              hit_tag = ''
            badge = f'{badge} {hit_tag}'
        return (f'<div class="rec-row">'
                f'<div class="rec-type">{label}</div>'
                f'<div class="rec-pick">{pick}</div>'
                f'<div class="rec-meta">{meta}</div>'
                f'<div class="rec-badge">{badge}</div>'
                f'</div>')

    # ── AI推荐卡 ──────────────────────────────────────
    ai_rows = make_row('wdl', '胜平负', required=True)
    for i in range(1, 4):
        ai_rows += make_row(f'score{i}', f'比分{i}')
    ai_rows += make_row('goals', '进球数', required=True)
    ai_card = (f'<div class="rec-card">'
               f'<div class="rec-card-head">{sec_head("bolt","AI推荐")}</div>'
               f'{ai_rows}</div>')

    # ── 深度推荐卡（有数据才显示）─────────────────────
    deep_rows = make_row('crowd_wdl', '胜平负')
    for i in range(1, 4):
        deep_rows += make_row(f'crowd_score{i}', f'比分{i}')
    if deep_rows:
        deep_card = (f'<div class="rec-card deep">'
                     f'<div class="rec-card-head">{sec_head("groups","深度推荐")}</div>'
                     f'{deep_rows}</div>')
    else:
        deep_card = ''

    return ai_card + deep_card


